import assert from "node:assert/strict";
import { BOOKS, TOTAL_CHAPTERS, getCanonicalBooks, getReadingBooks } from "../dist/data/bible-catalog.js";
import { completedChapterCount, completedBookCount, nextReadingBook, nextReadingChapter, markChapterComplete, isBookFinished } from "../dist/data/reading-progress.js";
import { getBibleTranslation, getBibleChapter } from "../dist/data/bible-rvr1909.js";
import { getBookEditorial } from "../dist/data/editorial-content.js";
assert.equal(BOOKS.length, 66);
assert.equal(TOTAL_CHAPTERS, 1189);
assert.equal(new Set(BOOKS.map(book=>book.id)).size, 66);
assert.equal(getReadingBooks()[0].name, "3 Juan");
assert.equal(getReadingBooks()[65].name, "Salmos");
assert.equal(getCanonicalBooks()[0].name, "Génesis");
assert.equal(getCanonicalBooks()[65].name, "Apocalipsis");
assert.equal(new Set(BOOKS.map(book=>book.canonicalOrder)).size,66);
assert.equal(BOOKS.filter(book=>book.testament==="old").length,39);
assert.equal(BOOKS.filter(book=>book.testament==="new").length,27);
const empty={completedChapters:{}};
assert.equal(completedBookCount(empty),0);
assert.equal(nextReadingBook(empty).id,"3-juan");
assert.equal(nextReadingChapter(empty,BOOKS[0]),1);
const progressed=markChapterComplete(empty,BOOKS[0],1);
assert.equal(completedBookCount(progressed),1);
assert.equal(completedChapterCount(progressed),1);
assert.equal(isBookFinished(progressed,BOOKS[0]),true);
assert.equal(nextReadingBook(progressed).id,"2-juan");
assert.equal(empty.completedChapters["3-juan"],undefined);
assert.deepEqual(markChapterComplete(progressed,BOOKS[0],1).completedChapters["3-juan"],[1]);
assert.equal(markChapterComplete(empty,BOOKS[0],2),empty);
assert.ok(getBibleTranslation("rvr1909"));
assert.ok(getBookEditorial("3-juan")?.video);
console.log("PASS: catalog, canonical/editorial routes, progress, translation and editorial data");
